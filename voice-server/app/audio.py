"""Decode untrusted audio with ffmpeg under hard limits, then split it."""
import math
import os
import subprocess
import tempfile
from dataclasses import dataclass

import numpy as np

from . import config


class AudioError(Exception):
    """Carries a stable machine-readable code and an HTTP status."""

    def __init__(self, code: str, status: int = 422):
        super().__init__(code)
        self.code = code
        self.status = status


@dataclass
class Decoded:
    samples: np.ndarray  # float32, mono, 16 kHz
    duration: float


def decode(data: bytes) -> Decoded:
    """Convert any supported container to 16 kHz mono float32.

    - the command is a fixed argument list (no shell, no user strings; the temp
      file name is generated by Python)
    - -protocol_whitelist file stops ffmpeg following URLs inside
      playlist-style files
    - -t caps how much is decoded; a timeout caps how long it may run
    """
    if not data:
        raise AudioError("empty", 400)
    fd, path = tempfile.mkstemp(prefix="clip-", suffix=".bin")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        cmd = [
            config.FFMPEG_BIN, "-nostdin", "-hide_banner", "-loglevel", "error",
            "-protocol_whitelist", "file",
            "-i", path,
            "-vn", "-sn", "-dn",
            "-t", str(config.FFMPEG_READ_SECONDS),
            "-ac", "1", "-ar", str(config.SAMPLE_RATE),
            "-f", "f32le", "pipe:1",
        ]
        try:
            proc = subprocess.run(
                cmd, capture_output=True, timeout=config.FFMPEG_TIMEOUT_S,
                shell=False, check=False,
            )
        except subprocess.TimeoutExpired:
            raise AudioError("invalid_audio")
        except FileNotFoundError:
            raise AudioError("internal", 500)
        if proc.returncode != 0 or not proc.stdout:
            raise AudioError("invalid_audio")
        raw = proc.stdout
        raw = raw[: len(raw) - (len(raw) % 4)]
        samples = np.frombuffer(raw, dtype=np.float32).copy()
    finally:
        try:
            os.remove(path)
        except OSError:
            pass

    if not np.all(np.isfinite(samples)):
        raise AudioError("invalid_audio")
    duration = len(samples) / config.SAMPLE_RATE
    if duration < config.MIN_SECONDS:
        raise AudioError("empty", 400)
    if duration > config.MAX_SECONDS + 0.5:
        raise AudioError("too_long")
    rms = float(np.sqrt(np.mean(np.square(samples))))
    if rms < config.SILENCE_RMS:
        raise AudioError("silent")
    return Decoded(samples=samples, duration=duration)


def split(samples: np.ndarray) -> list[np.ndarray]:
    """Split evenly into the fewest pieces of at most MAX_PIECE_SECONDS (no tiny tail)."""
    total = len(samples)
    n = max(1, math.ceil(total / (config.MAX_PIECE_SECONDS * config.SAMPLE_RATE)))
    bounds = np.linspace(0, total, n + 1, dtype=int)
    return [samples[bounds[i]:bounds[i + 1]] for i in range(n)]
